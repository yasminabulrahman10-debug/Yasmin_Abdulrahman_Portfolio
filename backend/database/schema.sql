CREATE DATABASE IF NOT EXISTS yasmin_portfolio CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE yasmin_portfolio;

CREATE TABLE IF NOT EXISTS admins (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 passwordHash VARCHAR(255) NOT NULL,
 isActive BOOLEAN NOT NULL DEFAULT TRUE,
 createdAt DATETIME NOT NULL,
 updatedAt DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS profile (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 fullName VARCHAR(180) NOT NULL,
 jobTitle VARCHAR(180), headline VARCHAR(255), summary TEXT,
 address VARCHAR(255), phone VARCHAR(50), email VARCHAR(190),
 nationality VARCHAR(100), languages VARCHAR(255),
 profileImage VARCHAR(500), cvFile VARCHAR(500), socialLinks JSON NOT NULL,
 createdAt DATETIME NOT NULL, updatedAt DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS projects (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(180) NOT NULL, slug VARCHAR(200) UNIQUE, description TEXT,
 technologies JSON NOT NULL, category VARCHAR(100),
 status ENUM('completed','in_progress','planned') DEFAULT 'completed',
 image VARCHAR(500), demoUrl VARCHAR(500), repositoryUrl VARCHAR(500),
 displayOrder INT DEFAULT 0, isPublished BOOLEAN DEFAULT TRUE,
 createdAt DATETIME NOT NULL, updatedAt DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS experiences (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, jobTitle VARCHAR(180) NOT NULL,
 company VARCHAR(180), period VARCHAR(100), description TEXT,
 displayOrder INT DEFAULT 0, isPublished BOOLEAN DEFAULT TRUE,
 createdAt DATETIME NOT NULL, updatedAt DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS education (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, degree VARCHAR(180) NOT NULL,
 institution VARCHAR(180), period VARCHAR(100), description TEXT,
 displayOrder INT DEFAULT 0, isPublished BOOLEAN DEFAULT TRUE,
 createdAt DATETIME NOT NULL, updatedAt DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS skills (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 category VARCHAR(100), level INT UNSIGNED DEFAULT 0, displayOrder INT DEFAULT 0,
 isPublished BOOLEAN DEFAULT TRUE, createdAt DATETIME NOT NULL, updatedAt DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS certificates (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(180) NOT NULL,
 issuer VARCHAR(180), issueDate VARCHAR(80), image VARCHAR(500), description TEXT,
 displayOrder INT DEFAULT 0, isPublished BOOLEAN DEFAULT TRUE,
 createdAt DATETIME NOT NULL, updatedAt DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS contact_messages (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(150) NOT NULL,
 email VARCHAR(190) NOT NULL, subject VARCHAR(200), message TEXT NOT NULL,
 isRead BOOLEAN DEFAULT FALSE, createdAt DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
